use anyhow::{Context, Result};
use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};

use crate::config::VmConfig;

pub struct SystemdGenerator;

impl SystemdGenerator {
    pub fn generate_unit(config: &VmConfig, config_path: &Path) -> String {
        let abs_path = std::fs::canonicalize(config_path)
            .unwrap_or_else(|_| config_path.to_path_buf());
        let desc = config
            .description
            .clone()
            .unwrap_or_else(|| format!("MicroVM {} ({})", config.name, config.backend));

        let mvmctl_bin = std::env::current_exe()
            .map(|p| p.to_string_lossy().to_string())
            .unwrap_or_else(|_| "/usr/local/bin/mvmctl".to_string());

        format!(
            r#"# Automatically generated by mvmctl for {name}
# Source: {src}

[Unit]
Description={desc}
Documentation=man:mvmctl(1)
SourcePath={src}
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
RuntimeDirectory=mvmctl
RuntimeDirectoryPreserve=yes
SyslogIdentifier=vm-{name}
ExecStart={bin} run "{src}"
ExecStop={bin} stop "{src}"
ExecStopPost=-{bin} clean "{src}"
TimeoutStopSec=60
Restart=no
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
"#,
            name = config.name,
            src = abs_path.display(),
            desc = desc,
            bin = mvmctl_bin
        )
    }

    pub fn run_systemd_generator(output_dir: &Path) -> Result<()> {
        fs::create_dir_all(output_dir)
            .with_context(|| format!("Failed to create generator directory {}", output_dir.display()))?;

        let mut search_dirs = Vec::new();
        if let Ok(custom) = std::env::var("MVMCTL_CONFIG_DIR") {
            search_dirs.push(PathBuf::from(custom));
        }
        search_dirs.push(PathBuf::from("/etc/mvmctl"));
        search_dirs.push(PathBuf::from("/etc/mvmctl/vms"));
        search_dirs.push(PathBuf::from("/usr/lib/mvmctl"));

        let mut seen = std::collections::HashSet::new();

        for dir in &search_dirs {
            if !dir.is_dir() {
                continue;
            }
            if let Ok(entries) = fs::read_dir(dir) {
                for entry in entries.flatten() {
                    let path = entry.path();
                    if path.is_file() && path.extension().and_then(|s| s.to_str()) == Some("json") {
                        let stem = path
                            .file_stem()
                            .and_then(|s| s.to_str())
                            .unwrap_or_default()
                            .to_string();

                        if seen.contains(&stem) {
                            continue;
                        }

                        if let Ok(config) = VmConfig::load_from_file(&path) {
                            seen.insert(config.name.clone());
                            let unit_name = format!("vm-{}.service", config.name);
                            let unit_path = output_dir.join(&unit_name);
                            let unit_content = Self::generate_unit(&config, &path);

                            if let Err(e) = fs::write(&unit_path, unit_content) {
                                eprintln!("Failed to write {}: {}", unit_path.display(), e);
                                continue;
                            }

                            if config.autostart {
                                let wants_dir = output_dir.join("multi-user.target.wants");
                                let _ = fs::create_dir_all(&wants_dir);
                                let link_path = wants_dir.join(&unit_name);
                                let _ = fs::remove_file(&link_path);
                                let rel_target = format!("../{}", unit_name);
                                let _ = symlink(rel_target, link_path);
                            }
                        }
                    }
                }
            }
        }

        Ok(())
    }

    pub fn write_static_unit(
        config: &VmConfig,
        config_path: &Path,
        dest_dir: &Path,
    ) -> Result<PathBuf> {
        fs::create_dir_all(dest_dir)
            .with_context(|| format!("Failed to create destination dir {}", dest_dir.display()))?;
        let unit_name = format!("vm-{}.service", config.name);
        let dest_file = dest_dir.join(&unit_name);
        let content = Self::generate_unit(config, config_path);
        fs::write(&dest_file, content)
            .with_context(|| format!("Failed to write unit file {}", dest_file.display()))?;
        Ok(dest_file)
    }
}
