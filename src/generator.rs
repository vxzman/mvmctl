use anyhow::{Context, Result};
use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};

use crate::config::VmConfig;
use crate::plan::ResolvedPlan;
use crate::registry::ResourceRegistry;
use crate::settings::{self, GlobalConfig};

pub struct SystemdGenerator;

impl SystemdGenerator {
    pub fn generate_unit(global: &GlobalConfig, config: &VmConfig, config_path: &Path) -> String {
        let abs_path =
            std::fs::canonicalize(config_path).unwrap_or_else(|_| config_path.to_path_buf());
        let desc = settings::escape_unit_field(
            &config
                .description
                .clone()
                .unwrap_or_else(|| format!("MicroVM {} ({})", config.name, config.backend)),
        );
        let bin = global.unit_binary();
        let src = abs_path.display().to_string();

        let mut after = global.systemd.after.clone();
        let mut requires = Vec::new();
        let mut mounts = Vec::new();
        for disk in &config.disks {
            let text = disk.path.to_string_lossy();
            if text.starts_with("/dev/") {
                let unit = format!("{}.device", settings::systemd_path_escape(&text));
                after.push(unit.clone());
                requires.push(unit);
            } else if text.starts_with('/') {
                mounts.push(text.to_string());
            }
        }

        let runtime_lines = if global.runtime_dir == Path::new("/run/mvmctl") {
            format!(
                "RuntimeDirectory=mvmctl\nRuntimeDirectoryMode={}\nRuntimeDirectoryPreserve=yes\n",
                global.runtime_dir_mode
            )
        } else {
            String::new()
        };

        let after_line = after.join(" ");
        let wants_line = global.systemd.wants.join(" ");
        let requires_line = if requires.is_empty() {
            String::new()
        } else {
            format!("Requires={}\n", requires.join(" "))
        };
        let mounts_line = if mounts.is_empty() {
            String::new()
        } else {
            format!("RequiresMountsFor={}\n", mounts.join(" "))
        };

        format!(
            r#"# Automatically generated by mvmctl for {name}
# Source: {src}

[Unit]
Description={desc}
Documentation=man:mvmctl(1)
SourcePath={src}
After={after_line}
Wants={wants_line}
{requires_line}{mounts_line}
[Service]
Type=simple
{runtime_lines}SyslogIdentifier=vm-{name}
ExecStart="{bin}" run "{src}"
ExecStop="{bin}" stop "{src}"
ExecStopPost=-"{bin}" clean "{src}"
TimeoutStopSec={timeout}
Restart=no
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
"#,
            name = config.name,
            src = src,
            desc = desc,
            bin = bin.display(),
            timeout = global.unit_stop_timeout(),
            runtime_lines = runtime_lines,
            after_line = after_line,
            wants_line = wants_line,
            requires_line = requires_line,
            mounts_line = mounts_line,
        )
    }

    pub fn run_systemd_generator(global: &GlobalConfig, output_dir: &Path) -> Result<()> {
        fs::create_dir_all(output_dir).with_context(|| {
            format!(
                "Failed to create generator directory {}",
                output_dir.display()
            )
        })?;

        let (registry, report) = ResourceRegistry::build_and_validate(global);

        if !report.errors.is_empty() {
            eprintln!("============================================================");
            eprintln!("[mvmctl-generator] Resource conflict detection found errors:");
            for err in &report.errors {
                eprintln!("  ! {err}");
            }
            eprintln!("============================================================");
        }

        for (name, path) in &registry.names {
            if report.conflicting_vms.contains(name) {
                eprintln!(
                    "[mvmctl-generator] FAILED: Skipping unit generation for conflicting VM '{name}' to prevent system disruption."
                );
                continue;
            }

            if let Ok(config) = VmConfig::load_from_file(path) {
                let plan = ResolvedPlan::compile(global, &config)?;
                let _ = plan.save_resolved(global);

                let unit_name = format!("vm-{}.service", config.name);
                let unit_path = output_dir.join(&unit_name);
                let unit_content = Self::generate_unit(global, &config, path);

                if let Err(e) = fs::write(&unit_path, unit_content) {
                    eprintln!("Failed to write {}: {e}", unit_path.display());
                    continue;
                }

                if config.autostart {
                    let wants_dir = output_dir.join("multi-user.target.wants");
                    let _ = fs::create_dir_all(&wants_dir);
                    let link_path = wants_dir.join(&unit_name);
                    let _ = fs::remove_file(&link_path);
                    let rel_target = format!("../{unit_name}");
                    let _ = symlink(rel_target, link_path);
                }
            }
        }

        Ok(())
    }

    pub fn write_static_unit(
        global: &GlobalConfig,
        config: &VmConfig,
        config_path: &Path,
        dest_dir: &Path,
    ) -> Result<PathBuf> {
        fs::create_dir_all(dest_dir)
            .with_context(|| format!("Failed to create destination dir {}", dest_dir.display()))?;
        let unit_name = format!("vm-{}.service", config.name);
        let dest_file = dest_dir.join(&unit_name);
        let content = Self::generate_unit(global, config, config_path);
        fs::write(&dest_file, content)
            .with_context(|| format!("Failed to write unit file {}", dest_file.display()))?;
        Ok(dest_file)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::settings::GlobalConfig;

    #[test]
    fn unit_includes_device_dependency_and_configured_timeout() {
        let mut global = GlobalConfig::from_json(
            r#"{"stop_timeout_secs":20,"systemd":{"timeout_stop_sec":40}}"#,
        )
        .unwrap();
        global.mvmctl_bin = PathBuf::from("/usr/local/bin/mvmctl");
        let cfg: VmConfig = serde_json::from_str(
            r#"{
                "name":"freebsd",
                "description":"line1\nExecStart=/bin/evil %h",
                "backend":"qemu",
                "boot":{"mode":"uefi"},
                "disks":[{"path":"/dev/ubuntu-vg/freebsd.disk"},{"path":"/var/lib/images/extra.qcow2"}]
            }"#,
        )
        .unwrap();
        let unit =
            SystemdGenerator::generate_unit(&global, &cfg, Path::new("/etc/mvmctl/freebsd.json"));
        assert!(unit.contains(r"Requires=dev-ubuntu\x2dvg-freebsd.disk.device"));
        assert!(unit.contains("RequiresMountsFor=/var/lib/images/extra.qcow2"));
        assert!(unit.contains("TimeoutStopSec=40"));
        assert!(unit.contains("Description=line1 ExecStart=/bin/evil %%h"));
        assert!(!unit
            .lines()
            .any(|line| line.starts_with("ExecStart=/bin/evil")));
    }
}
